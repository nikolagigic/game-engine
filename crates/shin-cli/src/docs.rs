//! `shin docs tools` (GE-029): the user guide's tools reference, generated
//! from the engine's tool registry so it cannot drift from the code.
//!
//! [`tools_markdown`] renders every tool in
//! [`ToolRegistry::with_engine_tools`] as Markdown: its name, its
//! description, and a table of its arguments (type, required, default,
//! description) read from the tool's JSON Schema. The output is committed
//! as `guide/src/reference/tools.md`; a test in this module regenerates it
//! and fails, naming the command to run, when the committed file is stale.

use std::fmt::Write as _;

use serde_json::{Map, Value};
use shin::tool::{ToolInfo, ToolRegistry};

/// Where the generated reference lives, relative to the repository root.
#[cfg(test)]
const REFERENCE_PATH: &str = "guide/src/reference/tools.md";

/// The command that regenerates the reference.
const REGENERATE_COMMAND: &str =
    "cargo run -p shin-cli -- docs tools > guide/src/reference/tools.md";

/// The tools reference as Markdown, for every tool in
/// [`ToolRegistry::with_engine_tools`], in registration order.
pub fn tools_markdown() -> String {
    render(&ToolRegistry::with_engine_tools().list())
}

/// Markdown for `tools`: a title, a generated-file notice, a list of
/// tool names, then one section per tool.
fn render(tools: &[ToolInfo]) -> String {
    let mut out = String::new();
    out.push_str("# Tools reference\n\n");
    out.push_str("<!-- GENERATED by `");
    out.push_str(REGENERATE_COMMAND);
    out.push_str("`. Do not edit by hand. -->\n\n");
    let _ = writeln!(
        out,
        "Every tool the engine registers (`ToolRegistry::with_engine_tools`), in \
         registration order: {} tools. This is what `shin-mcp`, a project run with \
         `--mcp`, and the editor's Console offer. Arguments are one JSON object; \
         vectors are arrays (`[x, y, z]`), colours are linear RGBA (`[r, g, b, a]`), \
         rotations are Euler angles in degrees applied in X, Y, Z order, and entity ids \
         are the numbers `entity.spawn` and `entity.list` return. Unknown argument names \
         are rejected.\n",
        tools.len()
    );
    for tool in tools {
        let _ = writeln!(out, "- [`{}`](#{})", tool.name, anchor(&tool.name));
    }
    for tool in tools {
        out.push('\n');
        let _ = writeln!(out, "## `{}`\n", tool.name);
        let _ = writeln!(out, "{}\n", escape_html(&tool.description));
        out.push_str(&arguments_table(&tool.input_schema));
    }
    out
}

/// `text` with `<` and `>` outside backtick code spans written as HTML
/// entities, so a placeholder such as `sphere-<segments>x<rings>` in a
/// description is not taken for an HTML tag. Code spans are left alone:
/// Markdown shows their contents literally.
fn escape_html(text: &str) -> String {
    text.split('`')
        .enumerate()
        .map(|(i, part)| {
            if i % 2 == 0 {
                part.replace('<', "&lt;").replace('>', "&gt;")
            } else {
                part.to_string()
            }
        })
        .collect::<Vec<_>>()
        .join("`")
}

/// The HTML id mdBook gives a `## \`name\`` heading: lower case, with
/// letters, digits, `_` and `-` kept and everything else (the `.` and the
/// backticks) dropped.
fn anchor(name: &str) -> String {
    name.chars()
        .filter(|c| c.is_ascii_alphanumeric() || *c == '_' || *c == '-')
        .map(|c| c.to_ascii_lowercase())
        .collect()
}

/// The Markdown table of `schema`'s top-level properties, or a sentence
/// when it has none.
fn arguments_table(schema: &Value) -> String {
    let empty = Map::new();
    let properties = schema
        .get("properties")
        .and_then(Value::as_object)
        .unwrap_or(&empty);
    if properties.is_empty() {
        return "Takes no arguments.\n".to_string();
    }
    let defs = schema.get("$defs").and_then(Value::as_object);
    let required: Vec<&str> = schema
        .get("required")
        .and_then(Value::as_array)
        .map(|r| r.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();

    let mut out = String::from("| Argument | Type | Required | Default | Description |\n");
    out.push_str("|---|---|---|---|---|\n");
    for (name, property) in properties {
        let required = if required.contains(&name.as_str()) {
            "yes"
        } else {
            "no"
        };
        let default = property
            .get("default")
            .map(|d| format!("`{d}`"))
            .unwrap_or_default();
        let description = property
            .get("description")
            .and_then(Value::as_str)
            .unwrap_or_default();
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} | {} |",
            name,
            cell(&type_name(property, defs)),
            required,
            cell(&default),
            cell(description)
        );
    }
    out
}

/// `text` as one table cell: on one line, with `|` escaped and `<`/`>`
/// outside code spans written as entities ([`escape_html`]).
fn cell(text: &str) -> String {
    let one_line = text.split_whitespace().collect::<Vec<_>>().join(" ");
    escape_html(&one_line).replace('|', "\\|")
}

/// A short, human-readable type for a property schema: `string`,
/// `integer`, `[number; 3]`, `"cube" | "sphere"`, `number[]`, ... A
/// nullable type (`["integer", "null"]`, how an optional argument appears)
/// is shown without the `null`; the Required column already says it may
/// be omitted.
fn type_name(schema: &Value, defs: Option<&Map<String, Value>>) -> String {
    if let Some(reference) = schema.get("$ref").and_then(Value::as_str) {
        let name = reference.rsplit('/').next().unwrap_or(reference);
        return match defs.and_then(|d| d.get(name)) {
            Some(target) => type_name(target, defs),
            None => name.to_string(),
        };
    }
    if let Some(value) = schema.get("const") {
        return value.to_string();
    }
    if let Some(values) = schema.get("enum").and_then(Value::as_array) {
        return join_alternatives(values.iter().map(Value::to_string));
    }
    for key in ["oneOf", "anyOf"] {
        if let Some(options) = schema.get(key).and_then(Value::as_array) {
            return join_alternatives(options.iter().map(|o| type_name(o, defs)));
        }
    }
    let types: Vec<&str> = match schema.get("type") {
        Some(Value::String(t)) => vec![t.as_str()],
        Some(Value::Array(ts)) => ts
            .iter()
            .filter_map(Value::as_str)
            .filter(|t| *t != "null")
            .collect(),
        _ => Vec::new(),
    };
    if types.is_empty() {
        return "any".to_string();
    }
    join_alternatives(types.into_iter().map(|t| match t {
        "array" => array_type(schema, defs),
        other => other.to_string(),
    }))
}

/// `[T; n]` for a fixed-size array, otherwise `T[]`.
fn array_type(schema: &Value, defs: Option<&Map<String, Value>>) -> String {
    let item = schema
        .get("items")
        .map(|items| type_name(items, defs))
        .unwrap_or_else(|| "any".to_string());
    let min = schema.get("minItems").and_then(Value::as_u64);
    let max = schema.get("maxItems").and_then(Value::as_u64);
    match (min, max) {
        (Some(n), Some(m)) if n == m => format!("[{item}; {n}]"),
        _ => format!("{item}[]"),
    }
}

/// `a | b | c`.
fn join_alternatives(items: impl Iterator<Item = String>) -> String {
    items.collect::<Vec<_>>().join(" | ")
}

#[cfg(test)]
mod tests {
    use std::path::Path;

    use serde_json::json;

    use super::*;

    /// The committed reference must be exactly what `shin docs tools`
    /// prints now. If this fails, a tool or its arguments changed: run the
    /// command in the message and commit the result.
    #[test]
    fn tools_reference_is_up_to_date() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../..")
            .join(REFERENCE_PATH);
        let committed = std::fs::read_to_string(&path).unwrap_or_else(|err| {
            panic!(
                "cannot read {} ({err}); generate it with `{REGENERATE_COMMAND}`",
                path.display()
            )
        });
        let generated = tools_markdown();
        assert!(
            committed == generated,
            "{REFERENCE_PATH} is out of date: a tool's name, description, or arguments \
             changed. Regenerate it with\n\n    {REGENERATE_COMMAND}\n\nand commit the result."
        );
    }

    #[test]
    fn every_engine_tool_has_a_section() {
        let markdown = tools_markdown();
        for tool in ToolRegistry::with_engine_tools().list() {
            assert!(
                markdown.contains(&format!("\n## `{}`\n", tool.name)),
                "no section for {}",
                tool.name
            );
        }
    }

    #[test]
    fn types_are_rendered_readably() {
        let defs = json!({
            "Kind": { "oneOf": [
                { "const": "cube", "type": "string" },
                { "const": "sphere", "type": "string" }
            ] }
        });
        let defs = defs.as_object();
        let name = |schema: Value| type_name(&schema, defs);
        assert_eq!(name(json!({ "type": "string" })), "string");
        assert_eq!(name(json!({ "type": ["integer", "null"] })), "integer");
        assert_eq!(
            name(json!({
                "type": ["array", "null"],
                "items": { "type": "number" },
                "minItems": 3, "maxItems": 3
            })),
            "[number; 3]"
        );
        assert_eq!(
            name(json!({ "type": "array", "items": { "type": "string" } })),
            "string[]"
        );
        assert_eq!(
            name(json!({ "$ref": "#/$defs/Kind" })),
            "\"cube\" | \"sphere\""
        );
        assert_eq!(name(json!({ "enum": ["a", 1] })), "\"a\" | 1");
        assert_eq!(name(json!({})), "any");
    }

    #[test]
    fn table_marks_required_and_defaults_and_escapes_pipes() {
        let schema = json!({
            "type": "object",
            "properties": {
                "steps": { "type": "integer", "default": 1, "description": "How many\nsteps." },
                "label": { "type": ["string", "null"], "description": "a | b" }
            },
            "required": ["steps"]
        });
        let table = arguments_table(&schema);
        assert!(table.contains("| `steps` | integer | yes | `1` | How many steps. |"));
        assert!(table.contains("| `label` | string | no |  | a \\| b |"));
        assert_eq!(
            arguments_table(&json!({ "type": "object" })),
            "Takes no arguments.\n"
        );
    }

    #[test]
    fn angle_brackets_are_escaped_outside_code_spans() {
        assert_eq!(
            escape_html("sphere-<segments>x<rings> or `a<b>`"),
            "sphere-&lt;segments&gt;x&lt;rings&gt; or `a<b>`"
        );
        assert_eq!(cell("x <y>\n| z"), "x &lt;y&gt; \\| z");
    }
}
